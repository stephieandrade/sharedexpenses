create table app_users (
    id            bigint generated by default as identity primary key,
    name          varchar(100) not null,
    email         varchar(255) not null,
    password_hash varchar(255) not null,
    constraint uk_app_users_email unique (email)
);

create table expense_groups (
    id          bigint generated by default as identity primary key,
    name        varchar(100) not null,
    description varchar(500),
    currency    varchar(3)   not null,
    creator_id  bigint       not null,
    created_at  timestamp with time zone not null,
    version     bigint       not null,
    constraint fk_expense_groups_creator foreign key (creator_id) references app_users (id)
);

create table group_members (
    group_id  bigint not null,
    user_id   bigint not null,
    joined_at timestamp with time zone not null,
    constraint uk_group_members unique (group_id, user_id),
    constraint fk_group_members_group foreign key (group_id) references expense_groups (id) on delete cascade,
    constraint fk_group_members_user foreign key (user_id) references app_users (id)
);

create table expenses (
    id           bigint generated by default as identity primary key,
    group_id     bigint         not null,
    description  varchar(200)   not null,
    amount       numeric(12, 2) not null,
    paid_by_id   bigint         not null,
    expense_date date           not null,
    split_type   varchar(20)    not null,
    constraint fk_expenses_group foreign key (group_id) references expense_groups (id) on delete cascade,
    constraint fk_expenses_paid_by foreign key (paid_by_id) references app_users (id),
    constraint ck_expenses_amount check (amount > 0),
    constraint ck_expenses_split_type check (split_type in ('EQUAL', 'AMOUNTS', 'PERCENTAGES'))
);

create index idx_expenses_group on expenses (group_id);

create table expense_shares (
    expense_id bigint         not null,
    user_id    bigint         not null,
    amount     numeric(12, 2) not null,
    constraint uk_expense_shares unique (expense_id, user_id),
    constraint fk_expense_shares_expense foreign key (expense_id) references expenses (id) on delete cascade,
    constraint fk_expense_shares_user foreign key (user_id) references app_users (id),
    constraint ck_expense_shares_amount check (amount >= 0)
);

create table payments (
    id           bigint generated by default as identity primary key,
    group_id     bigint         not null,
    from_user_id bigint         not null,
    to_user_id   bigint         not null,
    amount       numeric(12, 2) not null,
    payment_date date           not null,
    constraint fk_payments_group foreign key (group_id) references expense_groups (id) on delete cascade,
    constraint fk_payments_from_user foreign key (from_user_id) references app_users (id),
    constraint fk_payments_to_user foreign key (to_user_id) references app_users (id),
    constraint ck_payments_amount check (amount > 0),
    constraint ck_payments_different_users check (from_user_id <> to_user_id)
);

create index idx_payments_group on payments (group_id);
